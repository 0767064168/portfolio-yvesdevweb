-- 9. Table Messages (Formulaire de contact)
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  message TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'new',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Table Admins (Comptes d'administration)
CREATE TABLE IF NOT EXISTS public.admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'admin',
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Table Sessions (Sessions Express)
CREATE TABLE IF NOT EXISTS public.sessions (
  session_id VARCHAR(128) PRIMARY KEY,
  expires BIGINT NOT NULL,
  data TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON public.sessions (expires);

-- 12. Table Login Attempts (Sécurité brute-force)
CREATE TABLE IF NOT EXISTS public.login_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash CHAR(64) NOT NULL,
  attempted_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_login_attempts_ip_time ON public.login_attempts (ip_hash, attempted_at);

-- 13. Table Admin Activity (Journal d'activité)
CREATE TABLE IF NOT EXISTS public.admin_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT REFERENCES public.admins(id) ON DELETE SET NULL,
  action VARCHAR(120) NOT NULL,
  details VARCHAR(255) DEFAULT '',
  ip_hash CHAR(64) DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_admin_activity_created ON public.admin_activity (created_at);

-- 14. Table Interaction Events (Suivi clics/events)
CREATE TABLE IF NOT EXISTS public.interaction_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name VARCHAR(40) NOT NULL,
  ip_hash CHAR(64) DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_interaction_events_name_time ON public.interaction_events (event_name, created_at);

-- 15. Table Visits (Analytique des visites)
CREATE TABLE IF NOT EXISTS public.visits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path VARCHAR(255) NOT NULL,
  visited_at TIMESTAMPTZ DEFAULT NOW(),
  ip_hash CHAR(64) DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_visits_path_time ON public.visits (path, visited_at);

